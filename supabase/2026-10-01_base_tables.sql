-- 애플트랙 기본 테이블 (가장 먼저 실행)
-- 운영 Supabase(2026-11-01)의 테이블 구조를 조회해 그대로 옮긴 것입니다. 데이터는 들어 있지 않습니다.
-- 이후 SQL(2026-10-22_personal_accounts.sql 등)이 권한 규칙(RLS)·프로필·함수·추가 컬럼을 이어서 만듭니다.
-- 이미 운영 중인 DB에는 다시 실행할 필요가 없습니다(if not exists).
-- 참고: environment.id는 앱이 id 없이 행을 넣으므로 자동 번호(identity)로 적었습니다.

create table if not exists public.lots (
  id text not null,
  name text not null,
  variety text not null,
  harvest_date text,
  intake_date text not null,
  location text,
  sensor_id text,
  quantity double precision,
  storage text not null,
  mcp text not null,
  packaging text,
  firmness double precision,
  brix double precision,
  weight double precision,
  acidity double precision,
  notes text not null default ''::text,
  created_at text not null,
  owner_id uuid default auth.uid(),
  team_shared boolean not null default false,
  storage_start_date date,
  initial_measured_on date,
  initial_sample_count integer,
  details jsonb not null default '{}'::jsonb,
  constraint lots_pkey PRIMARY KEY (id),
  constraint lots_owner_id_fkey FOREIGN KEY (owner_id) REFERENCES auth.users(id) ON DELETE SET NULL,
  constraint lots_initial_sample_count_check CHECK (((initial_sample_count IS NULL) OR (initial_sample_count > 0)))
);

create table if not exists public.team_members (
  user_id uuid not null,
  constraint team_members_pkey PRIMARY KEY (user_id),
  constraint team_members_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE
);

create table if not exists public.environment (
  id bigint generated by default as identity not null,
  lot_id text not null,
  "timestamp" text not null,
  sensor_id text not null,
  temperature double precision not null,
  humidity double precision not null,
  constraint environment_lot_id_sensor_id_timestamp_key UNIQUE (lot_id, sensor_id, "timestamp"),
  constraint environment_pkey PRIMARY KEY (id),
  constraint environment_lot_id_fkey FOREIGN KEY (lot_id) REFERENCES lots(id)
);

create table if not exists public.files (
  id text not null,
  lot_id text not null,
  kind text not null,
  key text not null,
  name text not null,
  mime text not null,
  date text not null,
  notes text not null default ''::text,
  created_at text not null,
  constraint files_pkey PRIMARY KEY (id),
  constraint files_lot_id_fkey FOREIGN KEY (lot_id) REFERENCES lots(id)
);

create table if not exists public.observations (
  id text not null,
  lot_id text not null,
  date text not null,
  firmness double precision,
  brix double precision,
  weight double precision,
  defects text not null,
  sample_count integer,
  notes text not null,
  acidity numeric,
  tracked_weight numeric,
  details jsonb not null default '{}'::jsonb,
  constraint observations_pkey PRIMARY KEY (id),
  constraint observations_lot_id_fkey FOREIGN KEY (lot_id) REFERENCES lots(id)
);

create table if not exists public.predictions (
  id text not null,
  lot_id text not null,
  as_of text not null,
  result text not null,
  created_at text not null,
  constraint predictions_pkey PRIMARY KEY (id),
  constraint predictions_lot_id_fkey FOREIGN KEY (lot_id) REFERENCES lots(id)
);
